const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const { chromium, devices } = require("playwright");
const { PrismaClient } = require("@prisma/client");

const baseURL = "http://127.0.0.1:3108";
assert.equal(process.env.GEOFIELDS_QA, "1");
assert.equal(process.env.DATABASE_URL, "postgresql://shiftqa@127.0.0.1:55450/geofields_offline_test");
assert.ok(process.env.QA_PASSWORD, "Set the password for the isolated receipt-preview QA Manager.");
const db = new PrismaClient();

async function main() {
  const [identity] = await db.$queryRaw`SELECT current_database() AS db, current_user AS account`;
  assert.deepEqual(identity, { db: "geofields_offline_test", account: "shiftqa" });
  assert.equal(await db.user.count({ where: { NOT: { email: { endsWith: "@example.invalid" } } } }), 0);
  const project = await db.project.findFirstOrThrow({ where: { name: "Offline QA Project" } });
  const hole = "QA-TIMER-" + randomUUID().slice(0, 8);
  const browser = await chromium.launch();
  try {
    const context = await browser.newContext({ ...devices["iPhone 13"], baseURL, timezoneId: "UTC" });
    context.setDefaultTimeout(12000);
    let page = await context.newPage();
    const at = (minutes) => new Date(origin + minutes * 60000);
    const origin = Math.floor(Date.now() / 60000) * 60000 - 120 * 60000;
    const button = (name) => page.getByRole("button", { name, exact: true });
    const field = (name) => page.locator(`#report [name="${name}"]`);
    await page.goto("/login?next=%2Foffline-drilling.html");
    await page.getByLabel("Email").fill("receipt-preview@example.invalid");
    await page.getByLabel("Password").fill(process.env.QA_PASSWORD);
    await button("Sign In").click();
    await button("Prepare or refresh field setup").click();
    await page.getByText(/Ready for offline use/).waitFor();
    await context.setOffline(true);
    await page.reload();
    await button("Start report").click();
    assert.ok(await button("Drilling").isDisabled());
    await field("projectId").selectOption(project.id);
    await field("holeNumber").fill(hole);
    await field("shift").selectOption("NIGHT");
    await page.clock.setFixedTime(at(0));
    await button("Drilling").click();
    await page.getByText("Activity saved on this phone.", { exact: true }).waitFor();
    assert.ok(await field("projectId").isDisabled());
    await button("Save to send").click();
    await page.getByText(/Stop the timer, review the timeline/).waitFor();
    assert.equal(await db.drillReport.count({ where: { holeNumber: hole } }), 0);
    await page.close();
    page = await context.newPage();
    await page.clock.setFixedTime(at(20));
    await page.goto("/offline-drilling.html");
    await button("Resume running shift").click();
    await field("holeNumber").waitFor({ state: "visible" });
    assert.equal(await field("holeNumber").inputValue(), hole);
    assert.equal(await page.locator("#shift-clock").textContent(), "00:20:00");
    if (process.env.QA_SCREENSHOT) await page.locator("#shift-log").screenshot({ path: process.env.QA_SCREENSHOT });
    await button("Delay").click();
    await page.waitForFunction(() => document.querySelector("#shift-activity")?.textContent === "Delay");
    await page.clock.setFixedTime(at(50));
    await button("Standby").click();
    await page.waitForFunction(() => document.querySelector("#shift-activity")?.textContent === "Standby");
    await page.clock.setFixedTime(at(65));
    await button("Stop timing").click();
    await page.getByText(/Timing stopped/).waitFor();
    await page.getByRole("button", { name: /^Edit Drilling:/ }).click();
    const local = (m) => at(m).toISOString().slice(0, 16);
    await page.getByLabel("Ended", { exact: true }).fill(local(15));
    await button("Save time").click();
    await page.getByText(/Activity time updated/).waitFor();
    await button("Add missed activity").click();
    await page.locator("#shift-edit-activity").selectOption("standby");
    await page.getByLabel("Started", { exact: true }).fill(local(15));
    await page.getByLabel("Ended", { exact: true }).fill(local(20));
    await button("Save time").click();
    await page.getByText(/Logged: 0.25 h drilling .* 0.5 h delay .* 0.33 h standby/).waitFor();
    await button("Fill report hours").click();
    await page.getByText(/Report hours filled/).waitFor();
    assert.equal(await field("workHours").inputValue(), "0.25");
    assert.equal(await field("delayHours").inputValue(), "0.5");
    assert.equal(await field("standbyHours").inputValue(), "0.33");
    await field("fromMeter").fill("0");
    await field("toMeter").fill("5");
    await button("Save to send").click();
    await page.getByText(/Choose a delay reason/).waitFor();
    await field("delayReasonCategory").selectOption("RIG_BREAKDOWN");
    await button("Save to send").click();
    await page.getByText("Saved on this phone", { exact: true }).waitFor();
    assert.equal(await db.drillReport.count({ where: { holeNumber: hole } }), 0);
    await context.setOffline(false);
    await page.getByText("Sent to GeoFields", { exact: true }).waitFor();
    const rows = await db.drillReport.findMany({ where: { holeNumber: hole } });
    assert.equal(rows.length, 1);
    assert.equal(rows[0].approvalStatus, "SUBMITTED");
    assert.equal(rows[0].shift, "NIGHT");
    assert.equal(rows[0].workHours, 0.25);
    assert.equal(rows[0].delayHours, 0.5);
    assert.equal(rows[0].standbyHours, 0.33);

    await context.setOffline(true);
    await button("Start report").click();
    await field("holeNumber").fill(hole + "-MANUAL");
    await field("workHours").fill("1.25");
    await button("Save draft").click();
    await page.getByText(/Draft saved on this phone/).waitFor();
    await page.reload();
    await button("Resume draft").click();
    await field("workHours").waitFor({ state: "visible" });
    assert.equal(await field("workHours").inputValue(), "1.25");
    assert.equal(await db.drillReport.count({ where: { holeNumber: hole + "-MANUAL" } }), 0);
    console.log("Browser shift log passed: offline close/reopen, switching, backfill, delay reason, explicit send, one pending report, and manual draft recovery.");
  } finally {
    await browser.close();
  }
}

main().catch((error) => { console.error(error); process.exitCode = 1; }).finally(() => db.$disconnect());
